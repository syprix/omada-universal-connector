"""Static route registry for selected GET dispatches; never builds paths."""
from __future__ import annotations

from dataclasses import dataclass
import re

SCHEMA_REVISION = 2
_REF = re.compile(r"[0-9a-f]{24}")
_MSP_REF = re.compile(r"[A-Za-z0-9_-]{1,128}")
_VAR = re.compile(r"\{([a-z][a-z0-9_]*)\}")
_PUBLIC_METHODS = frozenset({"GET"})
_UPSTREAM_READ_METHODS = frozenset({"GET", "POST"})


class RegistryError(ValueError):
    """Invalid registry data or a request outside its declared routes."""


@dataclass(frozen=True)
class Operation:
    operation_id: str
    public_method: str
    public_template: str
    upstream_method: str
    upstream_template: str
    # upstream path variable -> fixed config source or validated public reference name
    path_bindings: tuple[tuple[str, str], ...] = ()
    extra_arguments: tuple[str, ...] = ()
    # Validated connector-only query inputs; they are never forwarded upstream.
    local_arguments: tuple[str, ...] = ()
    evidence: str = "unknown"
    max_response_bytes: int = 1_048_576
    max_items: int = 500
    # Alternative connector-only query groups. Exactly one group is accepted.
    local_argument_alternatives: tuple[tuple[str, ...], ...] = ()
    # Optional, validated upstream query inputs that may be omitted.
    optional_arguments: tuple[str, ...] = ()


def _vars(template: str) -> tuple[str, ...]:
    if not isinstance(template, str) or not template.startswith("/") or "?" in template:
        raise RegistryError("invalid path template")
    residue = _VAR.sub("", template)
    if "{" in residue or "}" in residue:
        raise RegistryError("invalid path variable")
    return tuple(_VAR.findall(template))


def _normalize(template: str) -> str:
    return _VAR.sub("{}", template).casefold()


@dataclass(frozen=True)
class OperationRegistry:
    """Immutable entries and strict public route matcher; no URL/path execution."""

    def __init__(self, entries: tuple[Operation, ...]):
        if not isinstance(entries, tuple):
            raise RegistryError("entries must be a tuple")
        ids: set[str] = set()
        routes: set[tuple[str, str]] = set()
        for item in entries:
            if not isinstance(item, Operation) or not re.fullmatch(r"[a-z][a-z0-9_]*", item.operation_id):
                raise RegistryError("invalid operation id")
            if item.operation_id in ids:
                raise RegistryError("duplicate operation id")
            ids.add(item.operation_id)
            if (item.public_method not in _PUBLIC_METHODS or
                    item.upstream_method not in _UPSTREAM_READ_METHODS or
                    (item.upstream_method == "POST" and
                     item.operation_id != "site_batch_interference_status_summary")):
                raise RegistryError("unsupported method")
            public_vars, upstream_vars = _vars(item.public_template), _vars(item.upstream_template)
            normalized_route = (item.public_method, _normalize(item.public_template))
            if normalized_route in routes:
                raise RegistryError("normalized route collision")
            routes.add(normalized_route)
            if len(set(public_vars)) != len(public_vars) or len(set(upstream_vars)) != len(upstream_vars):
                raise RegistryError("duplicate path variable")
            if not isinstance(item.path_bindings, tuple) or any(
                not isinstance(pair, tuple) or len(pair) != 2 for pair in item.path_bindings
            ):
                raise RegistryError("invalid path bindings")
            bindings = dict(item.path_bindings)
            if len(bindings) != len(item.path_bindings) or set(bindings) != set(upstream_vars):
                raise RegistryError("unbound upstream path variable")
            supported_extra = {
                (): "",
                ("pon_port",): "olt_onu_inventory_summary",
                ("page_number", "page_size"): ("olt_pon_port_config_page_summary",
                                                  "site_client_traffic_summary",
                                                  "site_vlan_affected_ports_summary",
                                                  "site_port_schedule_summary",
                                                  "site_routing_table_summary",
                                                  "site_allowed_application_summary",
                                                  "site_blocked_application_summary",
                                                  "controller_gateway_wan_status_summary",
                                                  "controller_upgrade_log_inventory"),
                ("pon_port", "page_number", "page_size"): "olt_onu_autofind_inventory_summary",
                ("vpn_type",): ("site_vpn_tunnel_summary",
                                "site_open_vpn_tunnel_summary",
                                "site_vpn_server_status_summary",
                                "site_vpn_client_status_summary",
                                "site_vpn_s2s_status_summary"),
                ("function",): "site_wan_port_availability_summary",
            }
            if (not isinstance(item.extra_arguments, tuple) or
                    item.extra_arguments not in supported_extra or
                    (item.extra_arguments and item.operation_id not in
                     ({supported_extra[item.extra_arguments]} if isinstance(
                         supported_extra[item.extra_arguments], str) else
                      set(supported_extra[item.extra_arguments]))) or
                    set(item.extra_arguments) & set(public_vars)):
                raise RegistryError("invalid extra arguments")
            supported_local = {
                ("category",): {"site_incident_category_counts"},
                ("client_name", "ssid_name"): {"site_client_identity_match"},
                ("start_ms", "end_ms"): {
                    "site_events", "site_events_window_summary", "site_alerts_window_summary",
                    "controller_threat_severity_summary", "client_outage_timeline",
                    "site_audit_log_window_summary", "controller_audit_log_window_summary",
                    "controller_events_window_summary", "controller_alerts_window_summary",
                    "site_recent_clients_summary"},
                ("start_ms", "end_ms", "archived"): {
                    "site_threat_window_summary"},
                ("type",): {"site_mac_auth_ssid_inventory"},
                ("device_type",): {"site_routing_table_summary"},
                ("vlan_id",): {"site_vlan_ssid_usage_summary", "site_vlan_device_usage_summary",
                               "site_vlan_port_support_summary", "site_vlan_affected_ports_summary",
                               "site_vlan_topology_summary", "site_vlan_topology_reference_count"},
            }
            supported_local_alternatives = {
                ("start_ms", "end_ms"): {"site_events"},
                ("start_ms", "end_ms", "page_number", "page_size"):
                    {"site_events"},
                ("start_ms", "end_ms", "page_number", "page_size", "expected_total"):
                    {"site_events"},
                ("start_local", "end_local", "time_zone"): {
                    "site_events", "site_events_window_summary", "site_alerts_window_summary",
                    "client_outage_timeline", "site_audit_log_window_summary",
                    "controller_audit_log_window_summary",
                    "controller_events_window_summary", "controller_alerts_window_summary"},
            }
            if (not isinstance(item.local_arguments, tuple) or
                    (item.local_arguments and
                     (item.local_arguments not in supported_local or
                      item.operation_id not in supported_local[item.local_arguments])) or
                    set(item.local_arguments) & (set(public_vars) | set(item.extra_arguments))):
                raise RegistryError("invalid local arguments")
            if (not isinstance(item.local_argument_alternatives, tuple) or
                    any(not isinstance(group, tuple) or not group or
                        group not in supported_local_alternatives or
                        item.operation_id not in supported_local_alternatives[group] or
                        len(set(group)) != len(group) or
                        set(group) & (set(public_vars) | set(item.extra_arguments) |
                                      set(item.local_arguments))
                        for group in item.local_argument_alternatives) or
                    len(set(item.local_argument_alternatives)) !=
                    len(item.local_argument_alternatives)):
                raise RegistryError("invalid local argument alternatives")
            supported_optional = {"site_lan_network_interface_summary": ("interface_type",)}
            if (not isinstance(item.optional_arguments, tuple) or
                    item.optional_arguments != supported_optional.get(item.operation_id, ()) or
                    set(item.optional_arguments) & (set(public_vars) | set(item.extra_arguments) |
                                                    set(item.local_arguments))):
                raise RegistryError("invalid optional arguments")
            if any(source not in {"$config", "$incident_context_mac"} and
                   source not in (set(public_vars) | set(item.extra_arguments) | set(item.local_arguments))
                   for source in bindings.values()):
                raise RegistryError("path binding is not reference-bound")
            if ("$incident_context_mac" in bindings.values() and
                    "incident_ref" not in public_vars):
                raise RegistryError("incident context requires an opaque incident reference")
            if any(name not in {"site_ref", "history_ref", "incident_ref", "device_ref", "gateway_ref", "switch_ref", "stack_ref", "client_ref", "ssid_ref", "wlan_group_ref", "network_ref", "wan_port_ref", "site_template_ref", "msp_ref", "customer_ref", "vpn_ref", "group_ref", "upgrade_log_ref", "family_id", "application_id", "port"}
                   for name in public_vars):
                raise RegistryError("unsupported public reference binding")
            if item.evidence != "unknown":
                raise RegistryError("candidate evidence must remain unknown")
            if type(item.max_response_bytes) is not int or not 1 <= item.max_response_bytes <= 16_777_216:
                raise RegistryError("invalid response limit")
            if type(item.max_items) is not int or not 1 <= item.max_items <= 10_000:
                raise RegistryError("invalid item limit")
        object.__setattr__(self, "_entries", entries)

    @property
    def entries(self) -> tuple[Operation, ...]:
        return self._entries

    def get(self, operation_id: str) -> Operation:
        for item in self._entries:
            if item.operation_id == operation_id:
                return item
        raise RegistryError("unknown operation")

    @staticmethod
    def local_argument_sets(item: Operation) -> tuple[tuple[str, ...], ...]:
        return (item.local_arguments, *item.local_argument_alternatives)

    def match(self, method: str, path: str) -> tuple[Operation, tuple[tuple[str, str], ...]]:
        if not isinstance(method, str) or not isinstance(path, str) or "?" in path:
            raise RegistryError("route not allowed")
        for item in self._entries:
            if item.public_method != method.upper():
                continue
            names = _vars(item.public_template)
            pattern = re.escape(item.public_template)
            for name in names:
                value_pattern = (r"(?:0|[1-9][0-9]{0,2}|[1-3][0-9]{3}|40[0-8][0-9]|409[0-6])"
                                 if name == "port" else
                                 r"[A-Za-z0-9_-]{1,128}" if name in {"msp_ref", "customer_ref"} else
                                 r"(?:0|[1-9][0-9]{0,9})" if name == "family_id" else
                                 r"[A-Za-z0-9_-]{1,64}" if name == "application_id" else
                                 r"[0-9a-f]{24}")
                pattern = pattern.replace(re.escape("{" + name + "}"),
                                          r"(?P<" + name + ">" + value_pattern + ")")
            found = re.fullmatch(pattern, path)
            if found:
                if ("family_id" in names and
                        int(found.group("family_id")) > (1 << 31) - 1):
                    continue
                return item, tuple(found.groupdict().items())
        raise RegistryError("route not allowed")


